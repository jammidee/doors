#!/bin/sh
# DOORS OS - Copyright (c) 2026 Joel Damaso <jammidee@gmail.com>, Philippines.
# The kernel's function table for stack traces (kernel/debug.c ksym_lookup).
#   nm -n --defined-only build/kernel0.elf | sh tools/gen_ksyms.sh > build/gen/ksyms.c
# With no input it writes an empty table (the first link). The table goes into .rodata, after
# .text, so linking it in moves no function (the Makefile checks that).
echo "/* DOORS OS - Copyright (c) 2026 Joel Damaso <jammidee@gmail.com>, Philippines. */"
echo "/* Generated by tools/gen_ksyms.sh from the first link of the kernel. Do not edit. */"
echo "#include <doors/types.h>"
awk '
BEGIN { n = 0 }
$2 ~ /^[tT]$/ && $3 !~ /^\./ { addr[n] = $1; name[n] = $3; n++ }
END {
	printf "const U64 ksym_addr[] = {\n"
	for (i = 0; i < n; i++) printf "\t0x%sULL,\n", addr[i]
	if (n == 0) printf "\t0\n"
	printf "};\nconst char *const ksym_name[] = {\n"
	for (i = 0; i < n; i++) printf "\t\"%s\",\n", name[i]
	if (n == 0) printf "\t\"\"\n"
	printf "};\nconst U32 ksym_count = %d;\n", n
}'
